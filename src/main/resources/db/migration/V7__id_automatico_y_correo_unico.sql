-- Parte 1. user_data: la columna id_user pasa a generarse sola (identity), igual que las demás tablas.
ALTER TABLE public.user_data
    ALTER COLUMN id_user ADD GENERATED BY DEFAULT AS IDENTITY;
-- El próximo id arranca después del mayor que ya exista (si la tabla está vacía, arranca en 1).
SELECT pg_catalog.setval(pg_get_serial_sequence('public.user_data', 'id_user'),
                         COALESCE((SELECT MAX(id_user) FROM public.user_data), 0) + 1, false);

